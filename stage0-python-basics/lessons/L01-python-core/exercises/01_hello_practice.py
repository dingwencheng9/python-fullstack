# ============================================================
# 演示：个人问候信息
# ============================================================

# 变量赋值（= 是赋值运算符，不是数学中的等于）
name = "张三"
age = 25
city = "北京"
hobby = "编程"

# f-string 格式化字符串
# f"..." 中的 {} 会替换为变量的值
greeting = f"大家好！我叫 {name}，今年 {age} 岁，来自 {city}，爱好是 {hobby}"

# print() 函数用于输出
print(greeting)

# 试试修改上面的变量，然后重新运行
print(f"姓名: {name}")
print(f"年龄: {age}")
print(f"城市: {city}")
print(f"爱好: {hobby}")

# ============================================================
# 思考题
# ============================================================
