# ============================================================
# 基础 f-string 用法
# ============================================================
print("=== 基础 f-string ===\n")

name = "张三"
age = 25
city = "北京"

# 基本用法
print(f"我叫 {name}，今年 {age} 岁，来自 {city}。")

# 表达式
a, b = 10, 20
print(f"{a} + {b} = {a + b}")

# 调用方法
text = "hello"
print(f"'{text}' 大写是 '{text.upper()}'")

# ============================================================
# 格式化说明符
# ============================================================
print("\n=== 格式化说明符 ===\n")

# 保留小数位数
pi = 3.14159265
print(f"Pi = {pi:.2f}")  # 保留两位小数
print(f"Pi = {pi:.4f}")  # 保留四位小数

# 数字格式化
price = 1234.5678
print(f"价格: {price:,.2f}")  # 千位分隔符

# 百分比
ratio = 0.756
print(f"完成度: {ratio:.1%}")  # 百分比格式

# 对齐
name = "Alice"
print(f"|{name:<10}|")  # 左对齐
print(f"|{name:>10}|")  # 右对齐
print(f"|{name:^10}|")  # 居中

# ============================================================
# 调试格式化（Python 3.8+）
# ============================================================
print("\n=== 调试格式化 ===\n")

x = 10
y = 20

# = 调试格式：在变量名后加 = 可同时显示变量名和值
print(f"{x = }")  # x = 10
print(f"{x + y = }")  # x + y = 30
print(f"{'hello' = }")  # 'hello' = hello

