# ============================================================
# 演示：for 循环基础（使用 range 代替固定序列）
# ============================================================
print("=== for 循环基础演示 ===\n")

print("使用 range(1, 6) 遍历 1 到 5:")
for i in range(1, 6):
    print(f"   i = {i}")

# ============================================================
# 演示：break 提前退出
# ============================================================
print("\n=== break 提前退出演示 ===\n")

print("在 i=3 时 break:")
for i in range(1, 6):
    if i == 3:
        print(f"   i={i} 时触发 break，退出循环")
        break
    print(f"   i = {i}")

# ============================================================
# 演示：continue 跳过迭代
# ============================================================
print("\n=== continue 跳过迭代演示 ===\n")

print("跳过偶数，只打印奇数:")
for i in range(1, 8):
    if i % 2 == 0:
        continue
    print(f"   i = {i} (奇数)")

# ============================================================
# 演示：循环 else 子句
# ============================================================
print("\n=== 循环 else 子句演示 ===\n")

print("查找数字 5 (存在):")
target = 5
for num in range(1, 8):
    if num == target:
        print(f"   找到 {target} ！")
        break
else:
    print(f"   {target} 不在序列中")

print("\n查找数字 5 (不存在):")
target = 5
for num in range(1, 4):
    if num == target:
        print(f"   找到 {target} ！")
        break
else:
    print(f"   {target} 不在序列中 → else 分支执行")

# ============================================================
# 演示：累加循环
# ============================================================
print("\n=== 累加循环演示 ===\n")

print("计算 1+2+3+4+5:")
total = 0
for i in range(1, 6):
    total += i
print(f"   1+2+3+4+5 = {total}")

# ============================================================
# 演示：累加直到条件满足
# ============================================================
print("\n=== 累加直到条件满足 ===\n")

print("累加 1, 2, 3，遇到 4 停止:")
total = 0
for i in range(1, 10):  # 使用 range 代替元组
    if i >= 4:
        break
    total += i
print(f"   结果: {total}")

# ============================================================
# 演示：while 循环
# ============================================================
print("\n=== while 循环演示 ===\n")

print("倒计时 5 → 1:")
n = 5
while n > 0:
    print(f"   {n}...")
    n -= 1
print("   发射！")

# ============================================================
# 演示：while 循环累加
# ============================================================
print("\n=== while 循环累加演示 ===\n")

print("计算 1×2×3×4×5:")
product = 1
for i in range(1, 6):
    product *= i
print(f"   1×2×3×4×5 = {product}")

# ============================================================
# 演示：嵌套循环
# ============================================================
print("\n=== 嵌套循环演示 ===\n")

print("打印 1-3 的乘法表:")
for i in range(1, 4):
    row = ""
    for j in range(1, 4):
        if row:
            row += ", "
        row += f"{i}×{j}={i*j}"
    print(f"   {row}")

