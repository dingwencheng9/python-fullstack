"""L03 练习3: 生成器与列表推导式

难度: ⭐⭐☆ (中等)
预计时间: 25 分钟
知识点: 列表推导式 vs 生成器表达式、生成器的惰性求值

学习方式:
本练习是"演示型练习"——代码已经完整实现，
你需要运行它，观察输出，理解代码的工作原理。

任务描述:
练习列表推导式和生成器表达式，对比两者的区别：
- 列表推导式：立即求值，返回列表
- 生成器表达式：惰性求值，按需生成

提示:
1. 列表推导式用 []: [x for x in range(5)]
2. 生成器表达式用 (): (x for x in range(5))
3. 生成器是迭代器，只能遍历一次
"""

# ============================================================
# 演示：列表推导式 vs 生成器表达式
# ============================================================
print("=== 列表推导式 vs 生成器表达式 ===\n")

# 平方和计算对比
print("计算 0 到 n-1 的平方和:")
for n in [5, 10, 100]:
    # 列表推导式方式
    squares_list = [i * i for i in range(n)]
    list_result = sum(squares_list)

    # 生成器表达式方式
    gen_expr = (i * i for i in range(n))
    gen_result = sum(gen_expr)

    status = '✓' if list_result == gen_result else '✗'
    print(f"{status} n={n}: 列表={list_result}, 生成器={gen_result}")

# ============================================================
# 演示：惰性求值
# ============================================================
print("\n=== 生成器惰性求值演示 ===\n")

data = [1, 2, 3, 4, 5]

# 列表推导式：立即计算所有元素
list_result = [x * x for x in data]
print(f"列表推导式: {list_result}")
print("  → 立即生成完整列表")

# 生成器表达式：惰性求值
gen_expr = (x * x for x in data)
print(f"\n生成器表达式: {gen_expr}")
print("  → 创建生成器对象，尚未计算")

# 消费前两个
first_two = [next(gen_expr), next(gen_expr)]
print(f"\n消费前2个: {first_two}")
print("  → 每调用 next() 才计算下一个")

# ============================================================
# 演示：内存占用对比
# ============================================================
print("\n=== 内存占用对比演示 ===\n")

# 大数据场景下，生成器更节省内存
n = 1000000

# 列表推导式：需要存储 n 个整数
list_comp = [x * 2 for x in range(n)]
print(f"列表推导式内存占用: ~{len(list_comp) * 8 / (1024*1024):.0f} MB (n个整数)")
print(f"  实际: {len(list_comp)} 个元素")

# 生成器表达式：只存储生成器对象
gen_expr = (x * 2 for x in range(n))
print(f"\n生成器表达式内存占用: ~0.1 KB (仅生成器对象)")
print("  → 惰性求值，按需生成，不占用大量内存")

# ============================================================
# 演示：生成器的限制
# ============================================================
print("\n=== 生成器限制演示 ===\n")

gen = (x for x in [1, 2, 3])
print(f"生成器: {gen}")
print(f"  第一次遍历: {list(gen)}")
print(f"  第二次遍历: {list(gen)}")
print("  （生成器只能遍历一次！）")

